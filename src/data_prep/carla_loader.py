def build_carla_dataloader(data_dir: str, split: str = "val", batch_size: int = 1,
                            weather_filter=None, distance_filter=None):
    """
    Build a DataLoader from the CARLA dataset.
    
    Returns images (B, 3, 640, 640) and a list of target dicts,
    matching the interface used by the nuScenes dataloader.
    
    Parameters
    ----------
    data_dir : str
        Path to the CARLA dataset root.
    split : str
        Dataset split: 'train', 'val', 'test', or 'all'.
    batch_size : int
        Batch size. Default: 1 (recommended for RTX 4050).
    weather_filter : str or list, optional
        Filter by weather condition(s).
    distance_filter : int or list, optional
        Filter by distance(s) in metres.
    
    Returns
    -------
    dataset : CARLADataset
    loader : DataLoader
    """
    from torch.utils.data import DataLoader
    
    dataset = CARLADataset(
        data_root=data_dir,
        split=split,
        weather_filter=weather_filter,
        distance_filter=distance_filter,
    )
    
    def collate_fn(batch):
        """Custom collate: stack images, collect targets as list of dicts."""
        images = torch.stack([s['image'] for s in batch])
        targets = []
        for s in batch:
            targets.append({
                'boxes': s['bboxes'],
                'labels': s['labels'],
            })
        return images, targets
    
    loader = DataLoader(
        dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=0,
        collate_fn=collate_fn,
        drop_last=False,
    )
    
    return dataset, loader


